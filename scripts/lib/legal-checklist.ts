import { flatten, LEGAL_MARK, type Messages } from "./i18n-csv";

export interface OpenMark {
  key: string;
  english: string;
  /** locales whose text for this key is missing the mark (they must match en: a mark is a property of the passage, not of a language) */
  missingIn: string[];
}

export function openMarks(messages: Messages): OpenMark[] {
  const en = flatten(messages.en);
  const uk = flatten(messages.uk);
  const nb = flatten(messages.nb);
  const marked = (o: Record<string, string>, k: string) => (o[k] ?? "").includes(LEGAL_MARK);
  const keys = new Set([...Object.keys(en), ...Object.keys(uk), ...Object.keys(nb)].filter((k) => marked(en, k) || marked(uk, k) || marked(nb, k)));
  return [...keys].map((key) => ({
    key,
    english: (en[key] ?? "").replace(LEGAL_MARK, "").trim(),
    missingIn: [["en", en], ["uk", uk], ["nb", nb]].filter(([, o]) => !marked(o as Record<string, string>, key)).map(([l]) => l as string),
  }));
}

/** Markdown for docs/legal-review-checklist.md. Generated: edit the message files, then run `npm run legal:checklist`. */
export function buildChecklist(messages: Messages): string {
  const marks = openMarks(messages);
  const lines = [
    "# Legal review checklist",
    "",
    "_Generated by `npm run legal:checklist` from `src/messages/*.json`. Do not edit by hand._",
    "",
    `The privacy policy (\`/privacy\`) and terms (\`/terms\`) were **prepared by the operator without professional legal advice**; both pages say so in a notice at the`,
    `top (\`legal.draftBanner\`, always shown: keep it unless a lawyer has really reviewed the text). What each statement was checked against, and what could not be`,
    `verified, is in \`docs/legal-accuracy-review.md\`. A passage that still asks an open question starts with \`${LEGAL_MARK}\` and is shown highlighted on the page; the`,
    "notice then adds that such passages are open questions (\`legal.openMarksNote\`). Remove a mark only when the sentence has been checked against the code and a source,",
    "and do it in all three language files (a mark belongs to the passage, not the language).",
    "",
    `**Open marks: ${marks.length}.** Run \`npm run legal:checklist -- --check\` before launch: it fails while any mark remains.`,
    "",
    "Also fill in (these are placeholders on the pages until set):",
    "",
    "* `NEXT_PUBLIC_OPERATOR_NAME` and `NEXT_PUBLIC_OPERATOR_COUNTRY`: who runs the service.",
    "* `NEXT_PUBLIC_CONTACT_EMAIL`: shown on both pages.",
    "* The date line (\"Last updated: ...\") in `legal.privacy.updated` and `legal.terms.updated`: change it whenever the text changes.",
    "",
    "| # | Key | Passage (English) |",
    "| --- | --- | --- |",
    ...marks.map((m, i) => `| ${i + 1} | \`${m.key}\` | ${m.english.replace(/\|/g, "\|")}${m.missingIn.length ? ` **(mark missing in ${m.missingIn.join(", ")})**` : ""} |`),
    "",
  ];
  return lines.join("\n");
}
